# --- Fork: DOS only, from a task whose SCF passed ------------------------------------

def _context(config, evidence=None):
    return {'dimension': config.get('dimensionality', {}).get('dimension', '3D'), **({'scf': evidence} if evidence else {})}


def fork_preview(source):
    """Read-only: the DOS spec, its suggestions on the source's verified SCF, and what they would generate."""
    from vasp_agent.workflow import parameter_specs, scf_reuse
    source = Path(source)
    reused = scf_reuse.verified_source(source)
    config = reused['config']
    refuse_2d(config)
    evidence = scf_evidence(source, config)
    item = parameter_specs.for_stage('dos')
    context = _context(config, evidence)
    described = parameter_specs.describe(item, context)
    defaults = {name: entry['value'] for name, entry in described['suggestions'].items()}
    built = build(config, item, parameter_specs.validate(item, defaults, context), evidence)
    return {'spec': described, 'defaults': defaults, 'context': {'dimension': context['dimension']},
            'scf_evidence': built['scf_evidence'], 'preview': {k: built[k] for k in ('incar', 'kpoints', 'blocked', 'program_checks')},
            'charge_sha256': reused['evidence']['hashes']['scf/CHGCAR'],
            'note': '预览由来源已校验的 SCF 证据生成；操作者选定参数后才新建目录，来源不改动。'}


def prepare_dos_fork(source, target, values, environment=None):
    """New directory that reuses source's verified evidence through SCF and runs only DOS.

    The source is never touched and SCF is never rerun. The values are validated
    against the current spec, and the inputs they generate on the source's SCF
    evidence must not be blocked -- refused before anything is written. The new
    task waits at the dos review and needs its own submission grant.
    """
    from vasp_agent.workflow import parameter_specs, scf_reuse, stage_gate
    from vasp_agent.workflow import stage_definitions as stages
    source, target = Path(source), Path(target)
    if target.exists() or source.resolve() == target.resolve():
        raise ValueError('DOS 派生必须使用不存在的新目录。')
    reused = scf_reuse.verified_source(source, environment)
    manifest, config, data, plan_data, files = (reused[k] for k in ('manifest', 'config', 'evidence', 'plan', 'files'))
    refuse_2d(config)
    item = parameter_specs.for_stage('dos')
    evidence = scf_evidence(source, config)
    context = _context(config)
    entry = parameter_specs.record_entry(item, values, context)
    base = ([e for e in config['stages'] if e['name'] in stages.BASE_STAGES] if 'stages' in config
            else [{'name': name, 'version': 1} for name in stages.BASE_STAGES])
    entries = base + [{'name': 'dos', 'version': max(stages.DEFINITIONS['dos'])}]
    forked = {k: v for k, v in config.items() if k != 'stage_parameters'}
    forked['stage_parameters'] = {'dos': entry}
    forked = scf_reuse.fork_config(forked, entries)
    if stages.definition(forked, 'dos')['parameter_spec'] != parameter_specs.reference(item):
        raise ValueError('本引擎 dos 阶段定义引用的规范版本与当前规范不同。')
    built = build(forked, item, entry['values'], evidence)
    if built['blocked']:
        raise ValueError('DOS 输入被程序阻断，未创建新目录：' + '；'.join(built['blocked']))
    target.mkdir(parents=True, exist_ok=False)
    scf_reuse.copy_files(source, target, files)
    shutil.copyfile(source / 'manifest.json', target / 'dos-source-manifest.json')
    core.save(target / 'config.json', forked)
    plan_data['stage_parameters'] = {'dos': parameter_specs.plan_entry(item, entry['values'], {})}
    core.save(target / 'input-plan.json', plan_data)
    with (target / 'PARAMETERS.md').open('a', encoding='utf-8') as stream:
        stream.write(f"\n\n### dos 阶段参数（规范 {item['id']} v{item['version']}，操作者确认，DOS 派生）\n```json\n"
                     + json.dumps(entry['values'], ensure_ascii=False, indent=1)
                     + '\n```\n复用来源 SCF 电荷密度（ICHARG=11），不重算 SCF；输入在阶段启动时由已校验的 SCF 证据生成并与审阅方案比对。\n')
    receipt = {'source': str(source), 'source_files': files, 'spec': entry['spec'], 'values': entry['values'],
               'scf_reused': True, 'scf_recomputed': False, 'charge_sha256': data['hashes']['scf/CHGCAR'],
               'executable_sha256': reused['executable_sha256'], 'scf_evidence': built['scf_evidence'],
               'generated_on_source': {k: built[k] for k in ('incar', 'kpoints')},
               'physics': '同结构、赝势和模型，沿用来源操作者确认；不复制审阅或提交授权', 'submitted': False}
    core.save(target / 'dos-fork.json', receipt)
    updated = dict(manifest)
    updated['hashes'] = dict(manifest['hashes'])
    for name in ('config.json', 'input-plan.json', 'PARAMETERS.md', 'dos-source-manifest.json', 'dos-fork.json'):
        updated['hashes'][name] = core.digest(target / name)
    checkpoint = {'completed': list(stages.through(forked, 'scf')), 'next': 'dos',
                  'evidence_hashes': stage_gate.evidence(target, 'dos')['hashes'], 'dos_fork': str(source)}
    if checkpoint['evidence_hashes'] != data['hashes']:
        raise ValueError('新目录证据与来源不一致；新目录未完成，不能提交。')
    core.save(target / 'checkpoint.json', checkpoint)
    core.save(target / 'workflow-state.json', {'status': 'awaiting_review', **checkpoint})
    scf_reuse.recheck_source(source, data)
    # Published last: an interrupted preparation cannot pass core.verify.
    core.save(target / 'manifest.json', updated)
    core.verify(target)
    context_data = stage_gate.context(target)
    if context_data['dos_plan']['incar'] != built['incar']:
        raise ValueError('新目录生成的 DOS 输入与来源证据不一致；新目录未完成，不能提交。')
    core.event(target, 'prepared_dos_fork', source=str(source), charge_sha256=data['hashes']['scf/CHGCAR'],
               values=entry['values'])
    return {'prepared': True, 'directory': str(target), 'phase': 'dos', 'scf_recomputed': False,
            'charge_sha256': data['hashes']['scf/CHGCAR'], 'values': entry['values'],
            'incar': {k: built['incar'][k] for k in ('ISMEAR', 'EMIN', 'EMAX', 'NEDOS', 'NBANDS', 'LORBIT', 'ICHARG')},
            'kpoints': built['kpoints'], 'snapshot': context_data['snapshot'], 'submitted': False,
            'next': '新目录已复用并验证 SCF；需 get_stage_review 审阅 dos 并单独提交授权。'}


def values_digest(values):
    return hashlib.sha256(json.dumps(values, sort_keys=True).encode()).hexdigest()[:6]
