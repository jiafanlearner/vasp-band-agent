"""Three-dimensional DOS stage: inputs from the accepted SCF, program checks, exports, DOS-only fork.

The DOS run is a non-self-consistent calculation on the SCF charge density
(ICHARG=11, LORBIT=11). Its inputs are generated by the parameter spec dos
(parameter_specs) from the operator-chosen values and the hash-verified SCF
evidence; the stage review shows exactly that plan (dos_plan, inside the review
snapshot) and the run regenerates it and refuses any difference.

Every acceptance condition below is enforced here, in code:

before the run (plan): SCF source and evidence; input consistency; mesh and
integration plan (tetrahedron only with a regular mesh of at least four
irreducible k-points, otherwise blocked with the operator's alternatives -- never
a silent switch to Gaussian); window, NEDOS and NBANDS capacity.

after the run (check_outputs): complete, finite outputs whose actual parameters
match the plan; the electron count from the integrated total DOS, integrated
from below the lowest band (semicore included) to the DOS run's E_F, against
NELECT within ELECTRON_COUNT_TOLERANCE; the highest band above the window at
every k-point; the E_F shift between the DOS run and SCF recorded (flagged, not
required to be zero); projected-DOS units and normalization stated, with no
requirement that projections sum to the total.

Two-dimensional slabs are refused (a later extension). See
docs/design/WORKFLOW_MODULES.md §7.
"""
import csv
import hashlib
import json
import shutil
from pathlib import Path

import numpy as np

import vasp_agent.workflow.vasp_band_agent as core

# Engine marker: engines with it run the dos stage and prepare DOS-only forks.
DOS_VERSION = 1
# |N(E_F) - NELECT| allowed for the integrated total DOS, electrons per cell.
# The integrated DOS VASP writes is exact at its grid points for the tetrahedron
# method; 0.05 e covers the linear interpolation to E_F between grid points and
# Gaussian tails at the stated margin. Not a physics threshold to relax.
ELECTRON_COUNT_TOLERANCE = 0.05
# The run's EMIN must lie at least this far below the lowest eigenvalue of the DOS run.
MIN_COUNT_CLEARANCE_EV = 0.5
# E_F(DOS) - E_F(SCF) beyond this is flagged in the report, never a failure.
FERMI_SHIFT_FLAG_EV = 0.1
ORBITAL_TYPES = ('s', 'p', 'd', 'f')
_trapezoid = getattr(np, 'trapezoid', None) or np.trapz
ENERGY_REFERENCE = {'kind': 'scf_fermi',
                    'note': '零点为 SCF 的 E_F（固定电荷密度的唯一自洽参考，与 bands.csv 的 energy_minus_scf_ef_eV 相同）；'
                            'DOS 计算自身的 E_F 与差值另行记录。'}
PROJECTION_NOTE = {'units': 'states/eV/cell',
                   'spin': 'ISPIN=1：总 DOS 与投影 DOS 均已包含自旋简并（因子 2），不再乘 2',
                   'projection': 'LORBIT=11：投影到各原子 PAW 球（半径取 POTCAR 的 RWIGS）上的 lm 分量，按元素与 l 求和',
                   'normalization': '投影只覆盖原子球；球外间隙与球重叠使投影之和不等于总 DOS，不要求二者相等',
                   'per_formula_unit': '需要每化学式单位时除以晶胞内化学式数'}
LIMITATIONS = ['k 网格加密倍数是初始策略，DOS 未做网格收敛证明。',
               '能量采样间隔不是分辨率；实际分辨率受 k 网格与积分方法限制。',
               'PBE Kohn-Sham DOS，非准粒子谱；非磁性、无 SOC。']


def refuse_2d(config):
    from vasp_agent.workflow.dimensionality import is_2d
    if is_2d(config):
        raise ValueError('二维 slab 的 DOS 尚未开放（后续扩展：真空方向网格、展宽选择与派生兼容测试补齐后再开放）；首版只支持三维体相。')


# --- SCF evidence -----------------------------------------------------------------

def scf_bands(root):
    """Absolute per-band minima and the lowest eigenvalue from the hash-verified scf/vasprun.xml."""
    from pymatgen.io.vasp.outputs import Vasprun
    folder = Path(root) / 'scf'
    run = Vasprun(folder / 'vasprun.xml', parse_dos=False, parse_projected_eigen=False, parse_potcar_file=False)
    arrays = [np.asarray(values)[:, :, 0] for values in run.eigenvalues.values()]
    if not arrays or any(a.ndim != 2 or not np.isfinite(a).all() for a in arrays):
        raise ValueError('scf/vasprun.xml 缺少有限的本征值，不能推导 DOS 输入。')
    minima = np.min(np.stack(arrays), axis=(0, 1))
    return {'band_minima_eV': minima.tolist(), 'lowest_eigenvalue_eV': float(minima.min()), 'kpoints': int(arrays[0].shape[0])}


def scf_evidence(root, config):
    """What the DOS inputs are derived from: the accepted SCF's verified files only."""
    from pymatgen.io.vasp.inputs import Kpoints
    root = Path(root)
    folder = root / 'scf'
    stamp = json.loads((folder / 'complete.json').read_text(encoding='utf-8'))
    if not stamp.get('xml_sha256') or core.digest(folder / 'vasprun.xml') != stamp['xml_sha256']:
        raise ValueError('scf/vasprun.xml 与完成记录不一致，不能作为 DOS 输入证据。')
    if not stamp.get('charge_sha256') or not (folder / 'CHGCAR').is_file() or core.digest(folder / 'CHGCAR') != stamp['charge_sha256']:
        raise ValueError('SCF 电荷文件与完成记录不一致（charge_sha256），不能用于 DOS。')
    summary = json.loads((root / 'scf-summary.json').read_text(encoding='utf-8'))
    kpoints = Kpoints.from_file(folder / 'KPOINTS')
    style = kpoints.style.name
    if style in ('Gamma', 'Monkhorst') and [int(n) for n in kpoints.kpts[0]] != [int(n) for n in summary['mesh']]:
        raise ValueError('scf/KPOINTS 与 scf-summary.json 的网格不一致，不能推导 DOS 网格。')
    bands = scf_bands(root)
    if len(bands['band_minima_eV']) != int(summary['nbands']):
        raise ValueError('scf/vasprun.xml 的能带数与 scf-summary.json 不一致。')
    efermi = float(summary['efermi'])
    return {'dimension': config.get('dimensionality', {}).get('dimension', '3D'),
            'scf_mesh': [int(n) for n in summary['mesh']], 'scf_kpoints_style': style, 'scf_fermi_eV': efermi,
            'scf_nbands': int(summary['nbands']), 'nelect': float(summary['nelect']),
            'band_minima_eV': [round(m - efermi, 6) for m in bands['band_minima_eV']],
            'lowest_eigenvalue_eV': round(bands['lowest_eigenvalue_eV'] - efermi, 6),
            'source': {'scf_vasprun_sha256': stamp['xml_sha256'], 'charge_sha256': stamp['charge_sha256'],
                       'scf_summary_sha256': core.digest(root / 'scf-summary.json'),
                       'scf_kpoints_sha256': core.digest(folder / 'KPOINTS'),
                       'note': 'E_F、NBANDS、NELECT、网格与各带最小值均取自上列已校验文件。'}}


# --- Plan (review) and run ----------------------------------------------------------

def spec_entry(config):
    from vasp_agent.workflow import parameter_specs, stage_definitions as stages
    entry = (config.get('stage_parameters') or {}).get('dos')
    if entry is None:
        raise ValueError('任务启用了 dos 阶段但没有已确认的 DOS 参数；请重新准备。')
    item, values = parameter_specs.check_record('dos', entry, {'dimension': config.get('dimensionality', {}).get('dimension', '3D')})
    if stages.definition(config, 'dos')['parameter_spec'] != parameter_specs.reference(item):
        raise ValueError('dos 阶段定义引用的参数规范版本与任务记录不同。')
    return item, values


def build(config, item, values, evidence):
    """INCAR (physics), KPOINTS and the program checks for these values on this evidence."""
    from vasp_agent.workflow.full_workflow import base_incar
    from vasp_agent.workflow.convergence_reuse import production_cutoff
    from vasp_agent.workflow import parameter_specs
    generated = item['generate'](values, evidence)
    encut = production_cutoff(config)
    incar = {**base_incar(config, encut), **generated['incar']}
    if incar['ISMEAR'] == -5:
        incar.pop('SIGMA', None)  # the tetrahedron method has no smearing width
    derived = generated['derived']
    integration = derived['integration']
    integration_ok = values['integration'] == 'gaussian' or (integration['regular_mesh'] and integration['kpoints_lower_bound']
                                                              >= parameter_specs.TETRAHEDRON_MIN_KPOINTS)
    window_ok = derived['nbands']['status'] != 'not_covered' and incar['NEDOS'] <= parameter_specs.MAX_NEDOS
    checks = {
        'scf_source': {'passed': True, 'scf_fermi_eV': evidence['scf_fermi_eV'], 'scf_nbands': evidence['scf_nbands'],
                       'nelect': evidence['nelect'], 'scf_mesh': evidence['scf_mesh'], **evidence['source']},
        'inputs': {'passed': evidence['dimension'] == '3D', 'encut': encut, 'charge': 'scf/CHGCAR',
                   'fixed': item['fixed'], 'same_as_scf': 'ENCUT、PREC、EDIFF、GGA、POTCAR 与 SCF 相同；ICHARG=11 不改变电荷密度'},
        'integration': {'passed': integration_ok, **integration, 'kmesh_factor': values['kmesh_factor'],
                        'mesh': generated['kpoints']['mesh'],
                        'note': '加密倍数是初始策略，不证明 DOS 已收敛。'},
        'window': {'passed': window_ok, 'plot_window_eV': derived['plot_window_eV'],
                   'counting_range': derived['counting_range'], 'EMIN': incar['EMIN'], 'EMAX': incar['EMAX'],
                   'NEDOS': incar['NEDOS'], 'sampling_interval_eV': derived['sampling_interval_eV'],
                   'grid_spacing_eV': derived['grid_spacing_eV'], 'sampling_note': derived['sampling_note'],
                   'nbands': derived['nbands']},
    }
    return {'spec': parameter_specs.reference(item), 'values': values, 'incar': incar,
            'kpoints': generated['kpoints'], 'derived': derived, 'blocked': generated['blocked'],
            'program_checks': checks, 'energy_reference': ENERGY_REFERENCE,
            'scf_evidence': {k: evidence[k] for k in ('scf_fermi_eV', 'scf_nbands', 'nelect', 'scf_mesh',
                                                      'scf_kpoints_style', 'lowest_eigenvalue_eV')}}


def plan(root, config):
    """The DOS run's inputs from the task's chosen values and its verified SCF evidence."""
    refuse_2d(config)
    item, values = spec_entry(config)
    return build(config, item, values, scf_evidence(root, config))


def review_context(root, config):
    """dos_plan for the stage review (inside the snapshot): what the run will use, and why it may be blocked."""
    data = plan(root, config)
    if data['blocked']:
        data['next'] = ('程序已阻断本阶段输入，不能放行。新任务的参数已写入 config，不能原地修改；'
                        '可用 request_dos_fork 从本任务已通过的 SCF 派生 DOS 新目录，由操作者按阻断原因改选参数。')
    return data


def kpoints_of(data):
    from pymatgen.io.vasp.inputs import Kpoints
    return Kpoints.gamma_automatic(data['kpoints']['mesh'])


def run(root, config, products):
    """STAGE_RUNNERS['dos']: generate, compare with the reviewed plan, run, check, export."""
    from vasp_agent.workflow import full_workflow
    data = plan(root, config)
    if data['blocked']:
        raise ValueError('DOS 输入被程序阻断，未启动计算：' + '；'.join(data['blocked']))
    core.save(root / 'dos-plan.json', data)
    kpoints = kpoints_of(data)
    result = full_workflow.stage(root, 'dos', products['primitive'], data['incar'], kpoints, products['command'],
                                 root / 'scf/CHGCAR', reviewed=(data['incar'], str(kpoints)))
    outputs = dos_data(result)
    checks = check_outputs(outputs, data)
    failed = [name for name, check in checks.items() if check['passed'] is False]
    report = dos_report(root, data, outputs, checks, failed)
    if failed:
        core.save(root / 'dos-report.json', report)
        raise ValueError('DOS 程序验收未通过：' + '；'.join(f"{name}: {checks[name]['reason']}" for name in failed))
    export(root, outputs, data, report)


# --- Outputs ------------------------------------------------------------------------

def dos_data(result):
    """Plain arrays from a parsed DOS run (pymatgen Vasprun with parse_dos=True)."""
    from pymatgen.electronic_structure.core import Spin
    spins = list(result.tdos.densities)
    if spins != [Spin.up]:
        raise ValueError('DOS 输出含自旋极化通道；当前只支持非磁性 ISPIN=1。')
    pdos = []
    for site in result.pdos or []:
        orbitals = {}
        for orbital, values in site.items():
            kind = getattr(getattr(orbital, 'orbital_type', None), 'name', None) or str(orbital)[0]
            orbitals.setdefault(kind, []).append(np.asarray(values[Spin.up], dtype=float))
        pdos.append({kind: np.sum(rows, axis=0) for kind, rows in orbitals.items()})
    eigen = None
    if result.eigenvalues:
        eigen = np.asarray(result.eigenvalues[Spin.up], dtype=float)
    return {'energies': np.asarray(result.tdos.energies, dtype=float),
            'total': np.asarray(result.tdos.densities[Spin.up], dtype=float),
            'integrated': np.asarray(result.idos.densities[Spin.up], dtype=float),
            'pdos': pdos, 'species': list(result.atomic_symbols), 'efermi': float(result.efermi),
            'parameters': dict(result.parameters), 'incar': dict(result.incar),
            'kpoints': len(result.actual_kpoints), 'weights': np.asarray(result.actual_kpoints_weights, dtype=float),
            'eigen': eigen}


def _check(passed, reason, **details):
    return {'passed': passed, 'reason': reason if passed is False else None, **details}


def check_outputs(outputs, data):
    """Post-run program checks; each item says what was compared and, when failed, why."""
    incar, derived = data['incar'], data['derived']
    energies, total, integrated = outputs['energies'], outputs['total'], outputs['integrated']
    checks = {}
    finite = all(np.all(np.isfinite(a)) for a in (energies, total, integrated)) and all(
        np.all(np.isfinite(v)) for site in outputs['pdos'] for v in site.values())
    complete = (finite and len(energies) == incar['NEDOS'] == len(total) == len(integrated)
                and bool(np.all(np.diff(energies) > 0)) and len(outputs['pdos']) == len(outputs['species']) > 0
                and all(outputs['pdos'])
                and all(len(v) == len(energies) for site in outputs['pdos'] for v in site.values()))
    checks['outputs'] = _check(complete, '总 DOS、积分 DOS 或投影 DOS 缺失、长度与 NEDOS 不符或含非有限值',
                               points=int(len(energies)), sites=len(outputs['pdos']), finite=bool(finite))
    if not complete:
        return checks
    spacing = (incar['EMAX'] - incar['EMIN']) / (incar['NEDOS'] - 1)
    actual = {key: outputs['incar'].get(key) for key in ('ICHARG', 'LORBIT', 'ISMEAR', 'NEDOS')}
    expected = {key: incar[key] for key in actual}
    nbands = int(outputs['parameters'].get('NBANDS', 0))
    mismatched = [k for k in actual if actual[k] != expected[k]]
    if nbands < incar['NBANDS']:
        mismatched.append('NBANDS')
    if abs(energies[0] - incar['EMIN']) > spacing + 1e-6 or abs(energies[-1] - incar['EMAX']) > spacing + 1e-6:
        mismatched.append('EMIN/EMAX')
    if incar['ISMEAR'] == -5 and outputs['kpoints'] < 4:
        mismatched.append('k 点数（四面体法需 ≥ 4）')
    checks['parameters'] = _check(not mismatched, '实际参数与方案不一致：' + '、'.join(mismatched),
                                  actual={**actual, 'NBANDS': nbands, 'EMIN': float(energies[0]), 'EMAX': float(energies[-1]),
                                          'irreducible_kpoints': outputs['kpoints']},
                                  planned={**expected, 'NBANDS': incar['NBANDS'], 'EMIN': incar['EMIN'], 'EMAX': incar['EMAX']},
                                  band_groups_note='VASP 可能把 NBANDS 向上取整到并行带组的倍数，实际值不小于方案即可。')
    efermi, nelect = outputs['efermi'], float(outputs['parameters'].get('NELECT', data['scf_evidence']['nelect']))
    method = ('Blöchl 修正四面体法（ISMEAR=-5）' if incar['ISMEAR'] == -5
              else f"Gaussian（ISMEAR=0，SIGMA={incar.get('SIGMA')} eV）")
    lowest = float(outputs['eigen'][:, :, 0].min()) if outputs['eigen'] is not None else None
    clearance = None if lowest is None else lowest - float(energies[0])
    counted = float(np.interp(efermi, energies, integrated))
    within = efermi >= energies[0] and efermi <= energies[-1]
    trapezoid = float(_trapezoid(total[energies <= efermi], energies[energies <= efermi]))
    count = {'integrated_dos_at_dos_fermi': round(counted, 6), 'nelect': nelect,
             'difference': round(counted - nelect, 6), 'tolerance': ELECTRON_COUNT_TOLERANCE,
             'lower_bound_eV': float(energies[0]), 'upper_bound': 'DOS 计算的 E_F', 'upper_bound_eV': efermi,
             'lowest_eigenvalue_eV': lowest, 'clearance_eV': None if clearance is None else round(clearance, 6),
             'minimum_clearance_eV': MIN_COUNT_CLEARANCE_EV, 'occupation_method': method,
             'normalization': 'ISPIN=1：VASP 总 DOS 已含自旋简并因子 2，积分直接与 NELECT 比较（不再乘 2）',
             'semicore': '积分下限低于 DOS 计算最低本征值（含 POTCAR ZVAL 计入的半芯态，如 Cu_pv 3p、La 5s5p）',
             'trapezoid_cross_check': round(trapezoid, 6), 'trapezoid_note': '对总 DOS 梯形积分，仅作交叉参考，不判定'}
    if outputs['eigen'] is not None and outputs['eigen'].shape[-1] == 2 and len(outputs['weights']) == outputs['eigen'].shape[0]:
        weights = outputs['weights'] / outputs['weights'].sum()
        occupied = float(2 * np.sum(weights[:, None] * outputs['eigen'][:, :, 1]))
        count['occupation_sum'] = round(occupied, 6)
        count['occupation_sum_note'] = 'Σ_k w_k Σ_n f_nk × 2（ISPIN=1），与能窗无关，仅作独立参考'
    if clearance is None or clearance < MIN_COUNT_CLEARANCE_EV:
        checks['electron_count'] = _check(False, f'积分下限 {energies[0]:.3f} eV 未低于最低能带（含半芯态）'
                                                 f' {lowest} eV 至少 {MIN_COUNT_CLEARANCE_EV} eV，积分必然少计电子', **count)
    elif not within:
        checks['electron_count'] = _check(False, 'DOS 计算的 E_F 不在能量网格内', **count)
    else:
        ok = abs(counted - nelect) <= ELECTRON_COUNT_TOLERANCE
        checks['electron_count'] = _check(ok, f'积分电子数 {counted:.4f} 与 NELECT {nelect:g} 相差 {counted - nelect:+.4f}，'
                                              f'超过容差 {ELECTRON_COUNT_TOLERANCE}', **count)
    scf_fermi = data['scf_evidence']['scf_fermi_eV']
    required = derived['nbands']['required_eV']
    if outputs['eigen'] is not None:
        top = float(outputs['eigen'][:, -1, 0].min()) - scf_fermi
        checks['empty_bands'] = _check(top >= required, f'最高能带最小值 {top:.3f} eV < 窗口上限 + 余量 {required} eV（相对 SCF E_F）；'
                                                        '需要更多 NBANDS（规范 nbands），或缩小窗口上限后重新派生',
                                       top_band_minimum_eV=round(top, 4), required_eV=required, nbands=nbands)
    else:
        checks['empty_bands'] = _check(False, 'DOS 输出缺少本征值，无法复核空带覆盖', required_eV=required)
    shift = efermi - scf_fermi
    checks['fermi_shift'] = _check(True, None, scf_fermi_eV=scf_fermi, dos_fermi_eV=efermi, shift_eV=round(shift, 6),
                                   flag_threshold_eV=FERMI_SHIFT_FLAG_EV, flagged=bool(abs(shift) > FERMI_SHIFT_FLAG_EV),
                                   note='记录而不要求相等：不同网格与占据方法重新积分非自洽本征值；绝缘体中 E_F 在带隙内的位置是任意的。')
    window = (energies >= scf_fermi + derived['plot_window_eV'][0]) & (energies <= scf_fermi + derived['plot_window_eV'][1])
    projected = sum(v for site in outputs['pdos'] for v in site.values())
    ratio = float(_trapezoid(projected[window], energies[window]) / max(_trapezoid(total[window], energies[window]), 1e-12))
    checks['projections'] = _check(True, None, **PROJECTION_NOTE, window_projected_to_total_ratio=round(ratio, 4),
                                   ratio_note='窗口内投影积分与总 DOS 积分之比，仅作说明；不要求为 1')
    return checks


def projections(outputs):
    """{element: {orbital type: array}} summed over the element's sites (states/eV/cell)."""
    data = {}
    for symbol, site in zip(outputs['species'], outputs['pdos']):
        target = data.setdefault(symbol, {})
        for kind, values in site.items():
            target[kind] = target.get(kind, 0) + values
    return {symbol: {kind: data[symbol][kind] for kind in ORBITAL_TYPES if kind in data[symbol]} for symbol in data}


def dos_report(root, data, outputs, checks, failed):
    return {'status': 'failed' if failed else 'passed', 'failed_checks': failed, 'stage': 'dos',
            'spec': data['spec'], 'values': data['values'], 'energy_reference': ENERGY_REFERENCE,
            'scf_fermi_energy_eV': data['scf_evidence']['scf_fermi_eV'], 'dos_fermi_energy_eV': outputs['efermi'],
            'fermi_shift_eV': checks.get('fermi_shift', {}).get('shift_eV'),
            'sampling_interval_eV': data['derived']['sampling_interval_eV'],
            'sampling_note': data['derived']['sampling_note'], 'kmesh': data['kpoints']['mesh'],
            'integration': data['derived']['integration']['method'], 'checks': checks,
            'projection': PROJECTION_NOTE, 'limitations': LIMITATIONS,
            'plan_sha256': core.digest(root / 'dos-plan.json') if (root / 'dos-plan.json').is_file() else None}


def csv_rows(outputs, scf_fermi):
    parts = projections(outputs)
    columns = [(f'{symbol}_{kind}', values) for symbol, orbitals in parts.items() for kind, values in orbitals.items()]
    header = ['energy_minus_scf_ef_eV', 'energy_eV', 'total_states_per_eV', 'integrated_states',
              *[name + '_states_per_eV' for name, _ in columns], 'scf_fermi_eV', 'dos_fermi_eV']
    rows = [[float(e - scf_fermi), float(e), float(outputs['total'][i]), float(outputs['integrated'][i]),
             *[float(values[i]) for _, values in columns], scf_fermi, outputs['efermi']]
            for i, e in enumerate(outputs['energies'])]
    return header, rows


def export(root, outputs, data, report):
    """dos.csv, dos.png/.pdf, the optional bands+DOS figure, dos-report.json and report.json['dos']."""
    from vasp_agent.workflow import dos_plot
    scf_fermi = data['scf_evidence']['scf_fermi_eV']
    header, rows = csv_rows(outputs, scf_fermi)
    with (root / 'dos.csv').open('w', newline='', encoding='utf-8') as out:
        writer = csv.writer(out)
        writer.writerow(header)
        writer.writerows(rows)
    parsed = dos_plot.parse_dos((root / 'dos.csv').read_text(encoding='utf-8'))
    title = dos_plot.title_for(root)
    window = tuple(data['derived']['plot_window_eV'])
    dos_plot.save(dos_plot.plot_dos(parsed, window, title), root / 'dos.png', root / 'dos.pdf')
    files = ['dos.csv', 'dos.png', 'dos.pdf']
    if (root / 'bands.csv').is_file():
        from vasp_agent.workflow.band_analysis import parse_bands
        bands = parse_bands((root / 'bands.csv').read_text(encoding='utf-8'))
        dos_plot.save(dos_plot.plot_combined(bands, parsed, window, title), root / 'bands-dos.png', root / 'bands-dos.pdf')
        files += ['bands-dos.png', 'bands-dos.pdf']
